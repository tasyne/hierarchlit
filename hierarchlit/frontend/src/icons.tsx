import {
  AlertTriangle,
  Archive,
  Box,
  CheckCircle2,
  Circle,
  CircleAlert,
  Cloud,
  Copy,
  Database,
  Download,
  ExternalLink,
  Eye,
  File,
  FileText,
  Folder,
  FolderOpen,
  Info,
  Lock,
  Pause,
  Pencil,
  Play,
  Plus,
  RefreshCw,
  Server,
  Settings,
  Table2,
  Trash2,
  Unlock,
  XCircle,
} from "lucide-react";
import type { LucideIcon } from "lucide-react";

const ICONS: Record<string, LucideIcon> = {
  alert: CircleAlert,
  archive: Archive,
  box: Box,
  bucket: Box,
  check: CheckCircle2,
  circle: Circle,
  cloud: Cloud,
  copy: Copy,
  database: Database,
  download: Download,
  error: XCircle,
  external: ExternalLink,
  eye: Eye,
  file: File,
  "file-text": FileText,
  folder: Folder,
  "folder-open": FolderOpen,
  info: Info,
  lock: Lock,
  pause: Pause,
  pencil: Pencil,
  play: Play,
  plus: Plus,
  refresh: RefreshCw,
  server: Server,
  settings: Settings,
  success: CheckCircle2,
  table: Table2,
  trash: Trash2,
  unlock: Unlock,
  warning: AlertTriangle,
};

export function Icon({ name, size = 15 }: { name: string | null; size?: number }) {
  const Glyph = (name && ICONS[name.toLowerCase()]) || Circle;
  return <Glyph aria-hidden size={size} strokeWidth={1.8} />;
}
